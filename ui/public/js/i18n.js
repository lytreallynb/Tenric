const dictionaries = { en, zh };
let lang = "zh";
try {
  lang = localStorage.getItem("tenric-ui-lang") ?? ((navigator.language ?? "").toLowerCase().startsWith("zh") ? "zh" : "en");
} catch { /* storage unavailable: keep the default */ }
if (!(lang in dictionaries)) lang = "en";

export const getLang = () => lang;
export function setLang(next) {
  lang = next;
  try { localStorage.setItem("tenric-ui-lang", next); } catch { /* not persisted */ }
}
/** Falls back to English, then to the key itself, so a missing string is visible and never blank. */
export const t = (key) => dictionaries[lang][key] ?? en[key] ?? key;
export const KEYS = { en: Object.keys(en), zh: Object.keys(zh) };
